CREATE TABLE maintenance_orders (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  titulo VARCHAR(150) NOT NULL,
  descripcion VARCHAR(500),
  tipo VARCHAR(20) NOT NULL,
  estado VARCHAR(20) NOT NULL,
  prioridad VARCHAR(20) NOT NULL,
  activo_id BIGINT NOT NULL,
  solicitante_id BIGINT NOT NULL,
  tecnico_id BIGINT NULL,
  fecha_programada DATE NULL,
  fecha_inicio TIMESTAMP NULL DEFAULT NULL,
  fecha_fin TIMESTAMP NULL DEFAULT NULL,
  costo DECIMAL(12,2) NULL,
  observaciones VARCHAR(500),
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion TIMESTAMP NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_orders_activo FOREIGN KEY (activo_id) REFERENCES assets(id),
  CONSTRAINT fk_orders_solicitante FOREIGN KEY (solicitante_id) REFERENCES users(id),
  CONSTRAINT fk_orders_tecnico FOREIGN KEY (tecnico_id) REFERENCES users(id),
  INDEX idx_orders_codigo (codigo),
  INDEX idx_orders_estado (estado),
  INDEX idx_orders_tipo (tipo),
  INDEX idx_orders_activo_id (activo_id),
  INDEX idx_orders_tecnico_id (tecnico_id),
  INDEX idx_orders_solicitante_id (solicitante_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE maintenance_reports (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  descripcion VARCHAR(500) NOT NULL,
  prioridad VARCHAR(20) NOT NULL,
  estado VARCHAR(20) NOT NULL,
  activo_id BIGINT NOT NULL,
  solicitante_id BIGINT NOT NULL,
  orden_id BIGINT NULL,
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion TIMESTAMP NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_reports_activo FOREIGN KEY (activo_id) REFERENCES assets(id),
  CONSTRAINT fk_reports_solicitante FOREIGN KEY (solicitante_id) REFERENCES users(id),
  CONSTRAINT fk_reports_orden FOREIGN KEY (orden_id) REFERENCES maintenance_orders(id),
  INDEX idx_reports_estado (estado),
  INDEX idx_reports_activo_id (activo_id),
  INDEX idx_reports_solicitante_id (solicitante_id),
  INDEX idx_reports_orden_id (orden_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
